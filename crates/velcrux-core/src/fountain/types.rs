//! Types, records, and wire representations for Dynamic Rateless Fountain Coding
//! & Loss-Resilient Erasure Streaming Engine (ADR-082).

use serde::{Deserialize, Serialize};

/// Magic bytes identifying Velcrux Fountain Container: "VFT1".
pub const FOUNTAIN_MAGIC: &[u8; 4] = b"VFT1";
/// Format version for Fountain containers.
pub const FOUNTAIN_VERSION: u8 = 1;

/// Configuration parameters for rateless Fountain encoding and decoding.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct FountainConfig {
    /// Payload size in bytes of each encoded symbol (default: 1024).
    pub symbol_size: usize,
    /// Robust Soliton distribution tuning parameter $c$ (default: 0.05).
    pub robust_c: f64,
    /// Failure probability bound $\delta$ for Soliton degree sampling (default: 0.05).
    pub robust_delta: f64,
    /// Whether first K symbols are systematic source blocks (default: true).
    pub systematic: bool,
}

impl Default for FountainConfig {
    fn default() -> Self {
        Self {
            symbol_size: 1024,
            robust_c: 0.05,
            robust_delta: 0.05,
            systematic: true,
        }
    }
}

impl FountainConfig {
    /// Validate configuration invariants.
    pub fn validate(&self) -> Result<(), FountainError> {
        if self.symbol_size == 0 {
            return Err(FountainError::ConfigError(
                "symbol_size must be strictly greater than 0".to_string(),
            ));
        }
        if self.robust_c <= 0.0 || self.robust_c >= 1.0 {
            return Err(FountainError::ConfigError(
                "robust_c parameter must be in range (0.0, 1.0)".to_string(),
            ));
        }
        if self.robust_delta <= 0.0 || self.robust_delta >= 1.0 {
            return Err(FountainError::ConfigError(
                "robust_delta parameter must be in range (0.0, 1.0)".to_string(),
            ));
        }
        Ok(())
    }
}

/// An individual rateless Fountain symbol generated by the encoder.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FountainSymbol {
    /// Encoding Symbol ID (ESI: 0, 1, 2, ... into infinity).
    pub esi: u32,
    /// Degree: number of original source symbols combined into this encoded symbol.
    pub degree: usize,
    /// Indices of original source symbols ($0..K-1$) combined via bitwise XOR.
    pub neighbors: Vec<usize>,
    /// Payload data of size `symbol_size`.
    pub data: Vec<u8>,
}

impl FountainSymbol {
    /// Serialize symbol into compact binary representation.
    #[must_use]
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut buf = Vec::with_capacity(8 + self.data.len());
        buf.extend_from_slice(&self.esi.to_le_bytes());
        buf.extend_from_slice(&(self.data.len() as u32).to_le_bytes());
        buf.extend_from_slice(&self.data);
        buf
    }

    /// Deserialize symbol from binary representation.
    pub fn from_bytes(
        buf: &[u8],
        k: usize,
        config: &FountainConfig,
    ) -> Result<Self, FountainError> {
        if buf.len() < 8 {
            return Err(FountainError::InvalidHeader(
                "Symbol buffer too short".to_string(),
            ));
        }
        let esi = u32::from_le_bytes(buf[0..4].try_into().unwrap());
        let len = u32::from_le_bytes(buf[4..8].try_into().unwrap()) as usize;
        if buf.len() < 8 + len {
            return Err(FountainError::InvalidHeader(
                "Truncated symbol payload".to_string(),
            ));
        }
        let data = buf[8..8 + len].to_vec();

        // Deterministically recompute degree and neighbors from ESI
        let (degree, neighbors) = super::distribution::sample_neighbors(esi, k, config);

        Ok(Self {
            esi,
            degree,
            neighbors,
            data,
        })
    }
}

/// Header metadata preceding a stream or container of Fountain symbols.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FountainHeader {
    /// Magic identifier ("VFT1").
    pub magic: [u8; 4],
    /// Header version (1).
    pub version: u8,
    /// Total byte length of original unpadded source data.
    pub original_len: u64,
    /// Number of source symbols (K).
    pub k_source_symbols: u32,
    /// Fixed payload size per symbol.
    pub symbol_size: u32,
    /// BLAKE3 cryptographic hash of original source data.
    pub blake3_hash: [u8; 32],
}

impl FountainHeader {
    /// Serialize header to 53-byte binary buffer.
    #[must_use]
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut buf = Vec::with_capacity(53);
        buf.extend_from_slice(&self.magic);
        buf.push(self.version);
        buf.extend_from_slice(&self.original_len.to_le_bytes());
        buf.extend_from_slice(&self.k_source_symbols.to_le_bytes());
        buf.extend_from_slice(&self.symbol_size.to_le_bytes());
        buf.extend_from_slice(&self.blake3_hash);
        buf
    }

    /// Parse header from 53-byte binary buffer.
    pub fn from_bytes(buf: &[u8]) -> Result<Self, FountainError> {
        if buf.len() < 53 {
            return Err(FountainError::InvalidHeader(format!(
                "Header length {} < 53 bytes",
                buf.len()
            )));
        }
        if &buf[0..4] != FOUNTAIN_MAGIC {
            return Err(FountainError::InvalidHeader(
                "Invalid magic bytes in Fountain header".to_string(),
            ));
        }
        if buf[4] != FOUNTAIN_VERSION {
            return Err(FountainError::InvalidHeader(format!(
                "Unsupported Fountain version {}",
                buf[4]
            )));
        }
        let original_len = u64::from_le_bytes(buf[5..13].try_into().unwrap());
        let k_source_symbols = u32::from_le_bytes(buf[13..17].try_into().unwrap());
        let symbol_size = u32::from_le_bytes(buf[17..21].try_into().unwrap());
        let mut blake3_hash = [0u8; 32];
        blake3_hash.copy_from_slice(&buf[21..53]);

        Ok(Self {
            magic: *FOUNTAIN_MAGIC,
            version: buf[4],
            original_len,
            k_source_symbols,
            symbol_size,
            blake3_hash,
        })
    }
}

/// A serialized container bundling header and encoded Fountain symbols.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FountainContainer {
    pub header: FountainHeader,
    pub symbols: Vec<FountainSymbol>,
}

impl FountainContainer {
    /// Serialize complete container to bytes.
    #[must_use]
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut buf = self.header.to_bytes();
        buf.extend_from_slice(&(self.symbols.len() as u32).to_le_bytes());
        for sym in &self.symbols {
            buf.extend_from_slice(&sym.to_bytes());
        }
        buf
    }

    /// Parse container from bytes.
    pub fn from_bytes(buf: &[u8], config: &FountainConfig) -> Result<Self, FountainError> {
        let header = FountainHeader::from_bytes(buf)?;
        if buf.len() < 57 {
            return Err(FountainError::InvalidHeader(
                "Truncated container".to_string(),
            ));
        }
        let count = u32::from_le_bytes(buf[53..57].try_into().unwrap()) as usize;
        let mut symbols = Vec::with_capacity(count);
        let mut offset = 57;

        for _ in 0..count {
            if offset + 8 > buf.len() {
                break;
            }
            let len = u32::from_le_bytes(buf[offset + 4..offset + 8].try_into().unwrap()) as usize;
            let end = offset + 8 + len;
            if end > buf.len() {
                return Err(FountainError::InvalidHeader(
                    "Truncated symbol in container".to_string(),
                ));
            }
            let sym = FountainSymbol::from_bytes(
                &buf[offset..end],
                header.k_source_symbols as usize,
                config,
            )?;
            symbols.push(sym);
            offset = end;
        }

        Ok(Self { header, symbols })
    }
}

/// Telemetry status of a Fountain decoding session.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FountainDecoderStatus {
    /// Number of source symbols to recover (K).
    pub k_source_symbols: usize,
    /// Total encoded symbols received so far.
    pub received_symbols: usize,
    /// Estimated additional symbols needed before full rank.
    pub symbols_needed: usize,
    /// Source symbols successfully decoded so far.
    pub decoded_source_symbols: usize,
    /// Whether all K source symbols have been reconstructed.
    pub is_complete: bool,
    /// Measured reception overhead percentage (($N - K) / K \times 100$).
    pub overhead_percentage: f64,
}

/// Comprehensive benchmark report evaluating Fountain codec performance.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FountainBenchmarkReport {
    /// Number of source blocks (K).
    pub k_source_symbols: usize,
    /// Size of each symbol in bytes.
    pub symbol_size_bytes: usize,
    /// Simulated packet loss probability (0.0 to 1.0).
    pub simulated_loss_rate: f64,
    /// Total source data volume in bytes.
    pub total_data_bytes: usize,
    /// Encoding throughput in MB/s.
    pub encode_throughput_mb_s: f64,
    /// Decoding throughput in MB/s.
    pub decode_throughput_mb_s: f64,
    /// Total symbols transmitted.
    pub symbols_transmitted: usize,
    /// Total symbols received across simulated lossy channel.
    pub symbols_received: usize,
    /// Total symbols dropped by simulated network loss.
    pub symbols_dropped: usize,
    /// Overhead symbols required beyond K to decode.
    pub overhead_symbols: usize,
    /// Overhead percentage: $(N_{\text{recv}} - K) / K \times 100$.
    pub overhead_percentage: f64,
    /// Cryptographic BLAKE3 verification match.
    pub blake3_match: bool,
}

/// Domain errors encountered during Fountain encoding or decoding.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error, Serialize, Deserialize)]
pub enum FountainError {
    #[error("Source data too short: must be at least 1 byte")]
    DataTooShort,

    #[error("Invalid Fountain container header: {0}")]
    InvalidHeader(String),

    #[error("Cryptographic BLAKE3 checksum mismatch: expected {expected}, calculated {actual}")]
    ChecksumMismatch { expected: String, actual: String },

    #[error("Insufficient symbols to solve linear system: required rank {required}, current rank {current}")]
    InsufficientSymbols { required: usize, current: usize },

    #[error("Fountain decoding failed: {0}")]
    DecodingFailed(String),

    #[error("Invalid Fountain configuration: {0}")]
    ConfigError(String),
}

/// Result alias for Fountain operations.
pub type FountainResult<T> = Result<T, FountainError>;
