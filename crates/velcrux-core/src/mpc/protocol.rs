#![forbid(unsafe_code)]

//! FROST (Flexible Round-Optimized Schnorr Threshold) Signing Protocol for Curve25519 / Ed25519.
//!
//! Features:
//! 1. Two-round distributed threshold signing without central key reconstruction.
//! 2. Binding factors $\rho_i$ mitigating Dlog forgery and concurrency replay attacks.
//! 3. Deterministic blame attribution pinpointing malicious or corrupted shares.
//! 4. 100% standard 64-byte Ed25519 wire format verifiable by any RFC 8032 verifier.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha512};

use super::curve::Point;
use super::scalar::Scalar;
use super::vss::{compute_lagrange_coefficient, SecretShare};
use crate::error::{ProtocolError, Result, VelcruxError};

/// Ephemeral nonces generated by a participant in Round 1.
pub struct SigningNonces {
    pub d: Scalar,
    pub e: Scalar,
}

impl SigningNonces {
    /// Clears sensitive nonce material.
    pub fn zeroize(&mut self) {
        self.d.zeroize();
        self.e.zeroize();
    }
}

impl Drop for SigningNonces {
    fn drop(&mut self) {
        self.zeroize();
    }
}

/// Round 1 public nonce commitments broadcast by each participant.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct NonceCommitment {
    /// 1-based participant identifier.
    pub participant_id: u32,
    /// $D_i = d_i \cdot B$.
    pub d_commitment: Point,
    /// $E_i = e_i \cdot B$.
    pub e_commitment: Point,
}

/// Package of public commitments collected for a signing round.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CommitmentPackage {
    pub commitments: Vec<NonceCommitment>,
}

impl CommitmentPackage {
    /// Extract quorum list of participating node IDs.
    pub fn quorum(&self) -> Vec<u32> {
        self.commitments.iter().map(|c| c.participant_id).collect()
    }

    /// Computes participant binding factor $\rho_i = H_{\text{bind}}(i, M, \text{commitments}) \pmod \ell$.
    pub fn compute_binding_factor(&self, participant_id: u32, message: &[u8]) -> Scalar {
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"velcrux-frost-binding:v1\n");
        hasher.update(&participant_id.to_le_bytes());
        hasher.update(message);

        for c in &self.commitments {
            hasher.update(&c.participant_id.to_le_bytes());
            hasher.update(&c.d_commitment.to_bytes());
            hasher.update(&c.e_commitment.to_bytes());
        }

        let mut output = [0u8; 64];
        let mut xof = hasher.finalize_xof();
        xof.fill(&mut output);
        Scalar::from_bytes_mod_order_wide(&output)
    }

    /// Computes group aggregate commitment $R = \sum_{j \in S} (D_j + \rho_j \cdot E_j)$.
    pub fn compute_group_commitment(&self, message: &[u8]) -> Point {
        let mut r = Point::IDENTITY;
        for c in &self.commitments {
            let rho = self.compute_binding_factor(c.participant_id, message);
            let term = c.d_commitment.add(&c.e_commitment.mul_scalar(&rho));
            r = r.add(&term);
        }
        r
    }
}

/// Partial signature share generated by a participant in Round 2.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SignatureShare {
    pub participant_id: u32,
    pub share: Scalar,
}

/// Master 64-byte Ed25519 threshold signature.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct ThresholdSignature {
    /// Aggregate group commitment point $R$.
    pub r: Point,
    /// Aggregate response scalar $z$.
    pub z: Scalar,
}

impl ThresholdSignature {
    /// Formats signature as standard 64-byte Ed25519 format: `[R (32 bytes) || z (32 bytes)]`.
    pub fn to_bytes(&self) -> [u8; 64] {
        let mut out = [0u8; 64];
        out[..32].copy_from_slice(&self.r.to_bytes());
        out[32..].copy_from_slice(&self.z.to_bytes_le());
        out
    }

    /// Parses signature from standard 64-byte Ed25519 wire format.
    pub fn from_bytes(bytes: &[u8; 64]) -> Result<Self> {
        let mut r_bytes = [0u8; 32];
        let mut z_bytes = [0u8; 32];
        r_bytes.copy_from_slice(&bytes[..32]);
        z_bytes.copy_from_slice(&bytes[32..]);

        let r = Point::from_bytes(&r_bytes).ok_or_else(|| {
            VelcruxError::Protocol(ProtocolError::Malformed("invalid R point in signature"))
        })?;
        let z = Scalar::from_bytes_le(&z_bytes);
        Ok(Self { r, z })
    }

    /// Converts signature to 128-character hexadecimal string.
    pub fn to_hex(&self) -> String {
        let bytes = self.to_bytes();
        let mut s = String::with_capacity(128);
        for b in bytes {
            s.push_str(&format!("{:02x}", b));
        }
        s
    }

    /// Parses signature from 128-character hexadecimal string.
    pub fn from_hex(s: &str) -> Result<Self> {
        let clean = s.trim().strip_prefix("0x").unwrap_or(s.trim());
        if clean.len() != 128 {
            return Err(VelcruxError::Protocol(ProtocolError::Malformed(
                "expected 128 hex characters for threshold signature",
            )));
        }
        let mut bytes = [0u8; 64];
        for i in 0..64 {
            let byte_val = u8::from_str_radix(&clean[i * 2..i * 2 + 2], 16).map_err(|_| {
                VelcruxError::Protocol(ProtocolError::Malformed("invalid hex digit in signature"))
            })?;
            bytes[i] = byte_val;
        }
        Self::from_bytes(&bytes)
    }

    /// Computes standard Ed25519 / RFC 8032 challenge $c = \text{SHA-512}(R \,||\, Y \,||\, M) \pmod \ell$.
    pub fn compute_challenge(r: &Point, group_public_key: &Point, message: &[u8]) -> Scalar {
        let mut hasher = Sha512::new();
        hasher.update(&r.to_bytes());
        hasher.update(&group_public_key.to_bytes());
        hasher.update(message);
        let digest = hasher.finalize();
        Scalar::from_bytes_mod_order_wide(&digest)
    }

    /// Verifies signature against master group public key $Y$:
    /// $z \cdot B \stackrel{?}{=} R + c \cdot Y$.
    pub fn verify(&self, group_public_key: &Point, message: &[u8]) -> bool {
        let c = Self::compute_challenge(&self.r, group_public_key, message);
        let lhs = Point::generator().mul_scalar(&self.z);
        let rhs = self.r.add(&group_public_key.mul_scalar(&c));
        lhs == rhs
    }
}

impl std::fmt::Debug for ThresholdSignature {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "ThresholdSignature({})", self.to_hex())
    }
}

impl std::fmt::Display for ThresholdSignature {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.to_hex())
    }
}

impl Serialize for ThresholdSignature {
    fn serialize<S>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        serializer.serialize_str(&self.to_hex())
    }
}

impl<'de> Deserialize<'de> for ThresholdSignature {
    fn deserialize<D>(deserializer: D) -> std::result::Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let s = String::deserialize(deserializer)?;
        Self::from_hex(&s).map_err(serde::de::Error::custom)
    }
}

/// Signer participant state in threshold scheme.
pub struct ThresholdSigner {
    pub participant_id: u32,
    pub share: SecretShare,
    pub group_public_key: Point,
    pub public_key: Point,
}

impl ThresholdSigner {
    pub fn new(share: SecretShare, group_public_key: Point) -> Self {
        let public_key = Point::generator().mul_scalar(&share.share);
        Self {
            participant_id: share.participant_id,
            share,
            group_public_key,
            public_key,
        }
    }

    /// Round 1: Sample random nonces $(d_i, e_i)$ and publish commitments $(D_i, E_i)$.
    pub fn round1_commit(&self) -> (SigningNonces, NonceCommitment) {
        let d = Scalar::random_nonzero();
        let e = Scalar::random_nonzero();

        let gen = Point::generator();
        let d_commitment = gen.mul_scalar(&d);
        let e_commitment = gen.mul_scalar(&e);

        let nonces = SigningNonces { d, e };
        let commitment = NonceCommitment {
            participant_id: self.participant_id,
            d_commitment,
            e_commitment,
        };

        (nonces, commitment)
    }

    /// Round 2: Generate signature share $z_i = d_i + e_i \rho_i + \lambda_i s_i c \pmod \ell$.
    pub fn round2_sign(
        &self,
        nonces: &SigningNonces,
        pkg: &CommitmentPackage,
        message: &[u8],
    ) -> Result<SignatureShare> {
        let quorum = pkg.quorum();
        if !quorum.contains(&self.participant_id) {
            return Err(VelcruxError::Protocol(ProtocolError::Malformed(
                "signer not in commitment package",
            )));
        }

        let lambda = compute_lagrange_coefficient(self.participant_id, &quorum)?;
        let rho = pkg.compute_binding_factor(self.participant_id, message);
        let r = pkg.compute_group_commitment(message);
        let c = ThresholdSignature::compute_challenge(&r, &self.group_public_key, message);

        // z_i = d_i + (e_i * rho_i) + (lambda_i * s_i * c) mod l
        let e_rho = nonces.e.mul(&rho);
        let d_plus_e_rho = nonces.d.add(&e_rho);

        let lambda_s = lambda.mul(&self.share.share);
        let lambda_s_c = lambda_s.mul(&c);

        let z_i = d_plus_e_rho.add(&lambda_s_c);

        Ok(SignatureShare {
            participant_id: self.participant_id,
            share: z_i,
        })
    }
}

/// Verifies a partial signature share with blame attribution:
/// $z_i \cdot B \stackrel{?}{=} D_i + \rho_i \cdot E_i + \lambda_i \cdot c \cdot Y_i$.
///
/// Returns `Ok(())` if valid; returns `Err` attributing fault to participant $i$ if invalid.
pub fn verify_signature_share(
    share: &SignatureShare,
    commitment: &NonceCommitment,
    participant_public_key: &Point,
    group_public_key: &Point,
    pkg: &CommitmentPackage,
    message: &[u8],
) -> Result<()> {
    let quorum = pkg.quorum();
    let lambda = compute_lagrange_coefficient(share.participant_id, &quorum)?;
    let rho = pkg.compute_binding_factor(share.participant_id, message);
    let r = pkg.compute_group_commitment(message);
    let c = ThresholdSignature::compute_challenge(&r, group_public_key, message);

    let lhs = Point::generator().mul_scalar(&share.share);

    let d_plus_rho_e = commitment
        .d_commitment
        .add(&commitment.e_commitment.mul_scalar(&rho));
    let lambda_c = lambda.mul(&c);
    let rhs = d_plus_rho_e.add(&participant_public_key.mul_scalar(&lambda_c));

    if lhs == rhs {
        Ok(())
    } else {
        Err(VelcruxError::Protocol(ProtocolError::InvalidIdentity(
            "detected invalid signature share: signer failed cryptographic share verification",
        )))
    }
}

/// Aggregates partial signature shares into a master 64-byte Ed25519 threshold signature:
/// $z = \sum_{i \in S} z_i \pmod \ell$.
pub fn aggregate_signature_shares(
    pkg: &CommitmentPackage,
    shares: &[SignatureShare],
    group_public_key: &Point,
    message: &[u8],
) -> Result<ThresholdSignature> {
    if shares.is_empty() {
        return Err(VelcruxError::Protocol(ProtocolError::Malformed(
            "cannot aggregate empty shares",
        )));
    }

    let mut z = Scalar::ZERO;
    for s in shares {
        z = z.add(&s.share);
    }

    let r = pkg.compute_group_commitment(message);
    let sig = ThresholdSignature { r, z };

    if !sig.verify(group_public_key, message) {
        return Err(VelcruxError::Protocol(ProtocolError::InvalidIdentity(
            "aggregated threshold signature verification failed",
        )));
    }

    Ok(sig)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mpc::vss::Polynomial;

    #[test]
    fn test_frost_threshold_signing_2_of_3() {
        let master_secret = Scalar::from_u64(999888777);
        let poly = Polynomial::random_with_secret(&master_secret, 2);
        let pkg = poly.commitments();
        let group_pubkey = pkg.group_public_key().expect("pubkey");
        let shares = poly.generate_shares(3);

        let signer1 = ThresholdSigner::new(shares[0].clone(), group_pubkey);
        let signer2 = ThresholdSigner::new(shares[1].clone(), group_pubkey);

        let msg = b"Cluster Root Authorization Token: Node 42";

        // Round 1
        let (nonces1, comm1) = signer1.round1_commit();
        let (nonces2, comm2) = signer2.round1_commit();

        let commit_pkg = CommitmentPackage {
            commitments: vec![comm1, comm2],
        };

        // Round 2
        let share1 = signer1.round2_sign(&nonces1, &commit_pkg, msg).unwrap();
        let share2 = signer2.round2_sign(&nonces2, &commit_pkg, msg).unwrap();

        // Verify partial shares individually
        verify_signature_share(
            &share1,
            &comm1,
            &signer1.public_key,
            &group_pubkey,
            &commit_pkg,
            msg,
        )
        .unwrap();
        verify_signature_share(
            &share2,
            &comm2,
            &signer2.public_key,
            &group_pubkey,
            &commit_pkg,
            msg,
        )
        .unwrap();

        // Aggregation
        let sig =
            aggregate_signature_shares(&commit_pkg, &[share1, share2], &group_pubkey, msg).unwrap();

        // Final verification
        assert!(sig.verify(&group_pubkey, msg));

        // Wire roundtrip
        let sig_bytes = sig.to_bytes();
        let recovered_sig = ThresholdSignature::from_bytes(&sig_bytes).unwrap();
        assert!(recovered_sig.verify(&group_pubkey, msg));
    }
}
